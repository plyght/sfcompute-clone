/**
 * Rewrites the source site's hashed CSS-module classes back into plain local
 * names and splits them into per-component *.module.css files.
 *
 *   careers-module__dH8buG__scroller      -> .scroller      (Careers.module.css)
 *   careers-roles-module__I1kqha__fill    -> .fill          (CareersRoles.module.css)
 *   cli-feature-module__oO3KOW__terminal  -> .terminal      (CliFeature.module.css)
 *
 * Rules are copied verbatim otherwise. Re-run after a fresh dump:
 *   node scripts/port-css-modules.mjs
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const SRC = new URL(
  '../site-dump/assets/sfcompute.com/vc-ap-d5fa6a/_next/static/immutable/chunks/2lozen1ojancq.css',
  import.meta.url,
).pathname;
const OUT = new URL('../src/components/', import.meta.url).pathname;

const MODULES = [
  { prefix: 'careers-module__dH8buG__', file: 'Careers.module.css' },
  { prefix: 'careers-roles-module__I1kqha__', file: 'CareersRoles.module.css' },
  { prefix: 'cli-feature-module__oO3KOW__', file: 'CliFeature.module.css' },
];

const css = await readFile(SRC, 'utf8');

/** Split top-level rules/at-rules, keeping each block whole. */
function topLevelBlocks(text) {
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) { out.push(text.slice(start, i + 1).trim()); start = i + 1; }
    }
  }
  return out.filter(Boolean);
}

const blocks = topLevelBlocks(css);
await mkdir(OUT, { recursive: true });

for (const { prefix, file } of MODULES) {
  const mine = blocks.filter((b) => b.includes(prefix));
  // strip the hash prefix everywhere, incl. @keyframes names and animation shorthands
  const body = mine.map((b) => b.split(prefix).join('')).join('\n\n');
  const header = `/* Ported verbatim from the source site's ${prefix.replace(/__.*/, '')} CSS module.\n   Generated by scripts/port-css-modules.mjs — edit the script, not this file. */\n\n`;
  await writeFile(OUT + file, header + body + '\n');
  console.log(`${file}: ${mine.length} rules`);
}
